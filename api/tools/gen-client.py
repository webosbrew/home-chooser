def js(value, indent=1):
    """JSON as a JS literal, indented with tabs to `indent` levels after the first line."""
    text = json.dumps(value, indent='\t', ensure_ascii=True, sort_keys=False)
    return text.replace('\n', '\n' + '\t' * indent)


def resolve(spec, schema):
    while isinstance(schema, dict) and '$ref' in schema:
        node = spec
        for part in schema['$ref'].split('#', 1)[1].split('/')[1:]:
            node = node[part]
        schema = node
    return schema


def flatten(spec, schema):
    """(properties, required) of an object schema made of $ref and allOf parts."""
    schema = resolve(spec, schema)
    props, required = {}, []

    def add(k, v):
        # Two plain schemas for one member (Failure's errorCode and a method's enum of codes) merge.
        if k in props and '$ref' not in props[k] and '$ref' not in v:
            props[k] = dict(props[k], **v)
        else:
            props.setdefault(k, v)
    for part in schema.get('allOf', []):
        p, r = flatten(spec, part)
        for k, v in p.items():
            add(k, v)
        required += [x for x in r if x not in required]
    for k, v in schema.get('properties', {}).items():
        add(k, v)
    required += [x for x in schema.get('required', []) if x not in required]
    return props, required


def branches(spec, method):
    """(success schema, failure schema) of a method's result: the oneOf branch with returnValue true and
    the one with returnValue false."""
    result = resolve(spec, method['result']['schema'])
    ok = bad = None
    for b in result['oneOf']:
        props, _ = flatten(spec, b)
        if props.get('returnValue', {}).get('const') is True:
            ok = b
        else:
            bad = b
    return ok, bad


def error_codes(spec, method):
    props, _ = flatten(spec, branches(spec, method)[1])
    return list(props['errorCode']['enum'])


def cap(name):
    return name[0].upper() + name[1:]


# ---- TypeScript ----

NAMED = ('AppId', 'App', 'RunningApp', 'LaunchPoint', 'Input', 'IconEntry')


def ts_type(spec, schema, indent):
    if isinstance(schema, dict) and '$ref' in schema:
        name = schema['$ref'].rsplit('/', 1)[1]
        if name in NAMED:
            return name
        if name == 'ApiVersion':
            return 'number'
        return ts_type(spec, resolve(spec, schema), indent)
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'oneOf' in schema:
        return '(%s)' % ' | '.join(ts_type(spec, s, indent) for s in schema['oneOf'])
    if 'allOf' in schema or schema.get('type') == 'object' or 'properties' in schema:
        props, required = flatten(spec, schema)
        return ts_object(spec, props, required, indent)
    t = schema.get('type')
    if t == 'array':
        return '%s[]' % ts_type(spec, schema.get('items', {}), indent)
    return {'string': 'string', 'boolean': 'boolean', 'integer': 'number', 'number': 'number'}.get(t, 'unknown')


def ts_doc(schema, pad):
    text = schema.get('description') if isinstance(schema, dict) else None
    return '%s/** %s */\n' % (pad, text) if text else ''


def ts_members(spec, props, required, indent):
    pad = '\t' * indent
    out = ''
    for name, schema in props.items():
        out += ts_doc(schema, pad)
        out += '%s%s%s: %s;\n' % (pad, name, '' if name in required else '?', ts_type(spec, schema, indent))
    return out


def ts_object(spec, props, required, indent):
    return '{\n%s%s}' % (ts_members(spec, props, required, indent + 1), '\t' * indent)


def dts(spec):
    schemas = spec['components']['schemas']
    perm = spec['x-permission']['group']
    out = ['// Types of homechooser.js, the Home Chooser launcher API client.', GENERATED,
           '// SPDX-License-Identifier: Apache-2.0', '',
           '// A <script> include defines the global HomeChooser; a CommonJS require returns the same object.',
           'export as namespace HomeChooser;', 'export = HomeChooser;', '', 'declare namespace HomeChooser {']
    out.append('\t/** %s */' % schemas['AppId']['description'])
    out.append('\ttype AppId = string;')
    for name in ('App', 'RunningApp', 'LaunchPoint', 'Input'):
        props, required = flatten(spec, schemas[name])
        doc = schemas[name].get('description')
        if doc:
            out.append('\t/** %s */' % doc)
        out.append('\tinterface %s %s' % (name, ts_object(spec, props, required, 1)))
    out.append('\t/** %s */' % schemas['IconEntry']['description'])
    out.append('\ttype IconEntry = %s;' % ' | '.join(ts_type(spec, b, 1) for b in schemas['IconEntry']['oneOf']))
    out.append('\t/** Members of every successful reply. More may be added at later levels; ignore unknown ones. */')
    out.append('\tinterface Success {\n\t\treturnValue: true;\n\t\tapiVersion: number;\n\t}')
    for m in spec['methods']:
        ok, _ = branches(spec, m)
        props, required = flatten(spec, ok)
        props = {k: v for k, v in props.items() if k not in ('returnValue', 'apiVersion')}
        out.append('\t/** The reply of %s when returnValue is true. */' % m['name'])
        out.append('\tinterface %sResult extends Success {\n%s\t}' % (cap(m['name']), ts_members(spec, props, required, 2)))
        out.append('\ttype %sErrorCode = %s;' % (cap(m['name']), ' | '.join(json.dumps(c) for c in error_codes(spec, m))))
        if m['params']:
            members = ''
            for p in m['params']:
                members += ts_doc(p, '\t\t')
                members += '\t\t%s%s: %s;\n' % (p['name'], '' if p.get('required') else '?', ts_type(spec, p['schema'], 2))
            out.append('\tinterface %sParams {\n%s\t}' % (cap(m['name']), members))
    out.append('''	/** A failure reply from Home Chooser (returnValue false, with apiVersion). */
	interface Failure {
		returnValue: false;
		apiVersion: number;
		errorCode: string;
		errorText: string;
	}
	/**
	 * Why a promise of this client rejected.
	 * source 'homechooser': Home Chooser answered with returnValue false; errorCode is one of the method's codes
	 *   (treat an unknown one as a failure too).
	 * source 'platform': the luna bus answered instead (no apiVersion): the service or method is unknown, or the
	 *   hub denied delivery. Home Chooser is absent or too old, or the permission was not installed with the app.
	 * source 'transport': nothing usable came back: no webOS service bridge, no reply within TIMEOUT_MS, or a
	 *   reply that is not JSON. errorCode is undefined.
	 */
	interface HomeChooserError extends Error {
		name: 'HomeChooserError';
		source: 'homechooser' | 'platform' | 'transport';
		/** Home Chooser's string code, or the platform's code (often a number). */
		errorCode?: string | number;
		/** Free text for logs; not a stable value. */
		errorText?: string;
		/** The same as errorCode (the name docs/launcher-api.md's bridge recipe uses). */
		code?: string | number;
		/** The whole reply, or {returnValue: false, errorText} for a transport failure. */
		reply: {[key: string]: unknown};
		/** The underlying error of a transport failure. */
		cause?: unknown;
	}
	const HomeChooserError: {
		new (reply: {[key: string]: unknown}, source: HomeChooserError['source'], cause?: unknown): HomeChooserError;
		prototype: HomeChooserError;
	};
''')
    out.append('\t/** The highest apiVersion level this client was generated for. Do not compare a reply against it with ===: use supports(level). */')
    out.append('\tconst API_VERSION: %d;' % spec['info']['x-apiVersion'])
    out.append('''	/**
	 * True when the apiVersion Home Chooser's replies have reported so far is at least level. Call getInfo first;
	 * false until a reply has come. Use supports(2) for listLaunchPoints, listInputs, getIcons and subscribe,
	 * never apiVersion === 1: levels only add.
	 */
	function supports(level: number): boolean;''')
    out.append('\tconst SERVICE: %s;' % json.dumps(spec['servers'][0]['url']))
    out.append('\tconst PERMISSION: %s;' % json.dumps(perm))
    out.append('\tconst HOME_CHOOSER_ID: %s;' % json.dumps(spec['x-requestLaunch']['payload']['id']))
    out.append('\t/** Per-call time limit of the bridge transport, in milliseconds. */')
    out.append('\tconst TIMEOUT_MS: %d;' % (spec['x-luna']['clientTimeoutSeconds'] * 1000))
    out.append('\t/** The errorCode values each method can send in v1. */')
    out.append('\tconst ERROR_CODES: {\n%s\t};' % ''.join(
        '\t\t%s: %sErrorCode[];\n' % (m['name'], cap(m['name'])) for m in spec['methods']))
    for m in spec['methods']:
        out.append('\t/** %s %s */' % (m['summary'], method_needs(m)))
        if m['params']:
            optional = all(not p.get('required') for p in m['params'])
            out.append('\tfunction %s(params%s: %sParams): Promise<%sResult>;' % (
                m['name'], '?' if optional else '', cap(m['name']), cap(m['name'])))
        else:
            out.append('\tfunction %s(params?: {}): Promise<%sResult>;' % (m['name'], cap(m['name'])))
    out.append('''	/** What subscribe returns: cancel() ends the subscription (the bus's own cancel). */
	interface Subscription {
		cancel(): void;
	}
%(subscribe)s
	/**
	 * Replaces the subscription transport (homechooser-mock.js uses it). fn(uri, payload, onMessage) starts a
	 * call that may answer many times, calls onMessage(reply) for each reply or onMessage(null, error) when the
	 * transport fails, and returns a function that cancels it. Pass nothing to restore the bridge.
	 */
	function setSubscribeTransport(transport?: (uri: string, payload: object,
		onMessage: (reply: {[key: string]: unknown} | null, error?: unknown) => void) => () => void): void;
	/**
	 * Asks the owner to make an app the Home app: launches Home Chooser with {request: appId}. A request only:
	 * the promise says whether the launch was accepted, not what the owner chose; call getInfo later and read
	 * isSelectedHome. appId defaults to ownAppId(); the promise rejects with a TypeError when there is none.
	 */
	function requestHome(appId?: AppId): Promise<{returnValue: true; [key: string]: unknown}>;
	/** This app's id, from PalmSystem.identifier (up to its first space); null outside the webOS web runtime. */
	function ownAppId(): AppId | null;
	/**
	 * One luna call through the transport. Resolves with the parsed reply whatever its returnValue; rejects only
	 * when there is no bridge, no reply within TIMEOUT_MS, or the reply is not JSON. Use it for platform calls,
	 * for example luna://com.webos.applicationManager/launch.
	 */
	function lunaCall(uri: string, payload?: object): Promise<{[key: string]: unknown}>;
	/**
	 * Replaces the webOS service bridge with another transport (homechooser-mock.js uses it). The function has
	 * lunaCall's contract. Pass nothing to restore the bridge.
	 */
	function setTransport(transport?: (uri: string, payload: object) => Promise<{[key: string]: unknown}>): void;
	/** Present only when homechooser-mock.js replaced the transport: the fake state, editable. */
	let mock: Mock | undefined;
	interface Mock {
		scenario: string;
		callerId: AppId | null;
		info: {version: string; root: boolean; permission: string; permitted: boolean; isSelectedHome: boolean};
		apps: App[];
		running: RunningApp[];
		foreground: {appId: string; windowId?: string; processId?: number};
		launchPoints: LaunchPoint[];
		inputs: Input[];
		/** App id (with "#largeIcon" for that size) -> {mimeType, data, byteLength}. */
		icons: {[id: string]: {mimeType: string; data: string; byteLength: number}};
		/** getIcons: "id:<app>", "launchPointId:<id>" or "inputId:<id>" (with "#largeIcon") -> an icon entry. */
		batchIcons: {[key: string]: IconEntry};
		/** Sends the subscribers of a method its current mock state again, as after a change. */
		notify(method: %(notify)s): void;
		/** Payloads of the applicationManager/launch calls made. */
		launches: object[];
		delayMs: number;
	}
}
''')
    subs = ''
    for m in spec['methods']:
        if m.get('x-subscribes'):
            subs += ('\t/** Subscribes to %s: onReply gets the whole reply now and again after every change; onError gets the\n'
                     '\t * failure that ended it (the subscription is over then). */\n'
                     '\tfunction subscribe(method: %s, params: %sParams | null, onReply: (reply: %sResult) => void,\n'
                     '\t\tonError?: (error: HomeChooserError) => void): Subscription;\n') % (
                m['name'], json.dumps(m['name']), cap(m['name']), cap(m['name']))
    notify = ' | '.join("'%s'" % m['name'] for m in spec['methods'] if m.get('x-subscribes'))
    return '\n'.join(out) % {'subscribe': subs.rstrip('\n'), 'notify': notify}


def or_list(names):
    return ', '.join(names[:-1]) + ' or ' + names[-1] if len(names) > 1 else ''.join(names)


def method_needs(m):
    needs = [what for key, what in (('x-needsRoot', 'root'), ('x-needsPermission', 'the permission'),
                                    ('x-needsSelectedHome', 'the selected Home')) if m.get(key)]
    return 'Needs %s.' % ', '.join(needs) if needs else 'Works for any app.'



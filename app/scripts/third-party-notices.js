// Generates ../THIRD_PARTY_NOTICES.md from package-lock.json and the installed packages' own package.json
// (production dependencies only, the whole tree). Run `npm ci` first, then `node scripts/third-party-notices.js`.
const fs = require('fs');
const path = require('path');

const appDir = path.resolve(__dirname, '..');

const licenseOf = (p) => {
	if (typeof p.license === 'string') return p.license;
	if (p.license && p.license.type) return p.license.type;
	if (Array.isArray(p.licenses)) return p.licenses.map((l) => l.type || l).join(' OR ');
	return 'UNKNOWN';
};
const repoOf = (p) => {
	const r = typeof p.repository === 'string' ? p.repository : p.repository && p.repository.url;
	return (r || p.homepage || '').replace(/^git\+/, '').replace(/\.git$/, '');
};

// Walk the production tree the way node resolves it: from each package, look for dependencies in its own
// node_modules, then upwards. peerDependencies are included because the installed copy is what ships.
const rows = [];
const seen = new Set();
const find = (from, name) => {
	for (let d = from; ; d = path.dirname(d)) {
		const c = path.join(d, 'node_modules', name);
		if (fs.existsSync(path.join(c, 'package.json'))) return c;
		if (d === path.dirname(d) || d.length <= path.dirname(appDir).length) return null;
	}
};
const visit = (dir) => {
	if (seen.has(dir)) return;
	seen.add(dir);
	const p = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
	if (dir !== appDir) {
		const files = fs.readdirSync(dir).filter((f) => /^(licen[sc]e|notice|copying)/i.test(f));
		rows.push({name: p.name, version: p.version, license: licenseOf(p), repo: repoOf(p), files});
	}
	for (const name of Object.keys(Object.assign({}, p.peerDependencies, p.dependencies, p.optionalDependencies))) {
		const c = find(dir, name);
		if (c) visit(c);
		else if (!(p.optionalDependencies || {})[name] && !(p.peerDependenciesMeta || {})[name]) {
			throw new Error('unresolved ' + name + ' from ' + dir);
		}
	}
};
visit(appDir);
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const out = [];
out.push('# Third-party notices', '');
out.push('Home Chooser itself is licensed under the Apache License 2.0 (see `LICENSE` and `NOTICE`). The package also contains the third-party components below.', '');
out.push('This file is generated by `app/scripts/third-party-notices.js` from the production dependency tree of `app/package.json` and each installed package\'s own `package.json`. Do not edit it by hand.', '');
out.push('## JavaScript dependencies (production)', '');
out.push('| Package | Version | Licence | Source |', '| --- | --- | --- | --- |');
for (const r of rows) out.push(`| ${r.name} | ${r.version} | ${r.license} | ${r.repo} |`);
out.push('');
const counts = {};
for (const r of rows) counts[r.license] = (counts[r.license] || 0) + 1;
out.push('Licence counts: ' + Object.entries(counts).sort().map(([k, v]) => `${k} ${v}`).join(', ') + '.', '');

out.push('## Fonts', '');
out.push('No Moonstone font files are bundled in the IPK. Enact prefers the TV\'s installed LG Smart UI and Moonstone fonts through CSS `local()` sources. The Miso and Museo Sans font files supplied with `@enact/moonstone` are removed from the package after the Enact build.', '');
fs.writeFileSync(path.join(appDir, '..', 'THIRD_PARTY_NOTICES.md'), out.join('\n'));
console.log('wrote THIRD_PARTY_NOTICES.md: ' + rows.length + ' packages');
